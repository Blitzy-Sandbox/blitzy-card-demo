package com.carddemo.dto;

import java.math.BigDecimal;

import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * Request payload for adding a new financial transaction (online transaction
 * {@code CT02}, legacy program {@code COTRN02C}).
 *
 * <p>This DTO is the Spring MVC / Jakarta Validation translation of the BMS input
 * map {@code COTRN02} ({@code app/cpy-bms/COTRN02.CPY}), backed by the
 * {@code TRAN-RECORD} layout ({@code app/cpy/CVTRA05Y.cpy}, record length 350).
 * Each legacy {@code RECEIVE MAP} field edit is reproduced here as a bean-validation
 * constraint, so malformed input is rejected at the controller boundary before the
 * service layer executes (RECEIVE MAP to bean validation).</p>
 *
 * <p>The transaction identifier is intentionally <strong>not</strong> a component of
 * this request: it is auto-generated by {@code TransactionAddService} at commit time,
 * mirroring the legacy auto-ID behaviour of {@code COTRN02C}. Never accept a
 * client-supplied transaction id.</p>
 *
 * <p>Monetary values use {@link java.math.BigDecimal} with scale 2 to preserve the
 * exact decimal fidelity of the COBOL {@code PIC S9(09)V99} amount; {@code float} and
 * {@code double} are never used for financial data. The {@link Digits} constraint
 * enforces at most 9 integer digits and at most 2 fraction digits, so an amount with
 * three or more decimal places is rejected. The service normalises the validated
 * amount to scale 2 (for example via {@code setScale(2, RoundingMode.HALF_UP)})
 * after validation succeeds.</p>
 *
 * <p>The request is fully stateless: the {@link #confirm()} flag replaces the legacy
 * CICS pseudo-conversational {@code COMMAREA} confirm-before-commit state. When
 * {@code confirm} is absent or {@code false} the service may return a preview; when it
 * is {@code true} (mapping the legacy {@code 'Y'} response) the service commits.</p>
 *
 * @param accountId          account number to post against (COBOL {@code ACTIDIN},
 *                           {@code X(11)}); required, 1 to 11 digits
 * @param cardNumber         card number for the transaction (COBOL {@code CARDNIN} /
 *                           {@code TRAN-CARD-NUM}, {@code X(16)}); required, 1 to 16 digits
 * @param typeCode           transaction type code (COBOL {@code TTYPCD} /
 *                           {@code TRAN-TYPE-CD}, {@code X(2)}); required
 * @param categoryCode       transaction category code (COBOL {@code TCATCD} /
 *                           {@code TRAN-CAT-CD}, {@code 9(4)}); optional, up to 4 digits
 * @param source             transaction source (COBOL {@code TRNSRC} /
 *                           {@code TRAN-SOURCE}, {@code X(10)}); optional
 * @param description        transaction description (COBOL {@code TDESC} /
 *                           {@code TRAN-DESC}, {@code X(100)}); optional, up to 100 chars
 * @param amount             transaction amount (COBOL {@code TRNAMT} /
 *                           {@code TRAN-AMT}, {@code S9(09)V99}); required, at most 9
 *                           integer and 2 fraction digits, scale 2
 * @param originalTimestamp  original transaction timestamp, kept as text to preserve the
 *                           legacy format (COBOL {@code TORIGDT} / {@code TRAN-ORIG-TS},
 *                           {@code X(26)}); optional
 * @param processedTimestamp processed transaction timestamp, kept as text to preserve the
 *                           legacy format (COBOL {@code TPROCDT} / {@code TRAN-PROC-TS},
 *                           {@code X(26)}); optional
 * @param merchantId         merchant identifier (COBOL {@code MID} /
 *                           {@code TRAN-MERCHANT-ID}, {@code 9(9)}); optional, up to 9 digits
 * @param merchantName       merchant name (COBOL {@code MNAME} /
 *                           {@code TRAN-MERCHANT-NAME}, {@code X(50)}); optional, up to 50 chars
 * @param merchantCity       merchant city (COBOL {@code MCITY} /
 *                           {@code TRAN-MERCHANT-CITY}, {@code X(50)}); optional, up to 50 chars
 * @param merchantZip        merchant ZIP / postal code (COBOL {@code MZIP} /
 *                           {@code TRAN-MERCHANT-ZIP}, {@code X(10)}); optional
 * @param confirm            confirm-before-commit flag; {@code true} commits,
 *                           {@code null} or {@code false} previews
 */
public record TransactionAddRequest(

        @NotBlank(message = "Account ID is required")
        @Size(max = 11, message = "Account ID must not exceed 11 characters")
        @Pattern(regexp = "\\d{1,11}", message = "Account ID must be 1 to 11 digits")
        String accountId,

        @NotBlank(message = "Card number is required")
        @Size(max = 16, message = "Card number must not exceed 16 characters")
        @Pattern(regexp = "\\d{1,16}", message = "Card number must be 1 to 16 digits")
        String cardNumber,

        @NotBlank(message = "Transaction type code is required")
        @Size(max = 2, message = "Transaction type code must not exceed 2 characters")
        String typeCode,

        @Size(max = 4, message = "Transaction category code must not exceed 4 characters")
        @Pattern(regexp = "\\d{1,4}", message = "Transaction category code must be 1 to 4 digits")
        String categoryCode,

        @Size(max = 10, message = "Transaction source must not exceed 10 characters")
        String source,

        @Size(max = 100, message = "Transaction description must not exceed 100 characters")
        String description,

        @NotNull(message = "Transaction amount is required")
        @Digits(integer = 9, fraction = 2,
                message = "Transaction amount must have at most 9 integer and 2 fraction digits")
        BigDecimal amount,

        @Size(max = 26, message = "Original timestamp must not exceed 26 characters")
        String originalTimestamp,

        @Size(max = 26, message = "Processed timestamp must not exceed 26 characters")
        String processedTimestamp,

        @Size(max = 9, message = "Merchant ID must not exceed 9 characters")
        @Pattern(regexp = "\\d{1,9}", message = "Merchant ID must be 1 to 9 digits")
        String merchantId,

        @Size(max = 50, message = "Merchant name must not exceed 50 characters")
        String merchantName,

        @Size(max = 50, message = "Merchant city must not exceed 50 characters")
        String merchantCity,

        @Size(max = 10, message = "Merchant ZIP must not exceed 10 characters")
        String merchantZip,

        Boolean confirm

) {
}
